export function themeWords(theme) {
  return theme.words
    .split(/\s+/)
    .map((w) => w.trim().toUpperCase())
    .filter(Boolean);
}

export function themeStats(theme) {
  const words = themeWords(theme);
  let longest = '';
  words.forEach((w) => {
    if (w.length > longest.length) longest = w;
  });
  return { count: words.length, longest, longestLen: longest.length };
}
